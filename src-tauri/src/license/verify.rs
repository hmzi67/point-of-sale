//! Signature and shape verification of a licence-status payload.
//!
//! Pure: bytes in, a trusted [`LicensePayload`] out (or an error). Nothing
//! here reads the clock, the database, or the network — that is what makes
//! it possible to test every rejection path exhaustively below.
//!
//! Order of operations is the whole point: the payload's JSON is parsed for
//! *nothing but its key id* until the signature has been checked. Only a
//! payload whose signature verifies under a compiled-in public key gets
//! deserialised into fields the app will act on.

use base64::engine::general_purpose::STANDARD as BASE64;
use base64::Engine;
use ed25519_dalek::{Signature, VerifyingKey};
use serde::{Deserialize, Serialize};

/// Payload shape this build understands. Must equal
/// `LicenseSigner::PAYLOAD_VERSION` on the server; a payload with a
/// different `v` is rejected before any field is trusted, so a future
/// incompatible server change can't be half-read by an old build.
pub const PAYLOAD_VERSION: u32 = 1;

/// Every public key this build accepts, by key id (`kid`).
///
/// Generated by the server repo's `scripts/generate-license-signing-key.php`;
/// the matching private half lives only in the server's `.env`. Listing more
/// than one is how a rotation works: ship a build that accepts both, switch
/// the server to the new key, then drop the old id a release or two later.
///
/// A compiled-in `const` rather than a file or a setting on purpose — a
/// runtime-swappable key would let anyone point the app at a keypair they
/// generated themselves. (A patched binary can of course still swap it; see
/// `vendor_gate.rs`'s LIMITS note — no client-side check survives that, and
/// this one doesn't claim to.)
pub const ACCEPTED_PUBLIC_KEYS: &[(&str, [u8; 32])] = &[(
    "2026-09",
    [
        0x48, 0x88, 0xd0, 0x13, 0xda, 0xef, 0x62, 0x68, 0x4c, 0xf9, 0x2b, 0x6e, 0x49, 0x3e, 0x34, 0xad,
        0x3d, 0xf6, 0xdd, 0x87, 0x74, 0xad, 0x07, 0x30, 0x97, 0x33, 0x98, 0x6e, 0x68, 0xb3, 0x64, 0x2d,
    ],
)];

/// Entitlement as the server reported it at `issued_at`.
///
/// `Unknown` absorbs any value a newer server might add: it is treated as
/// "not active" everywhere, which fails closed, rather than as a parse
/// error, which would make the app refuse a perfectly valid signed payload
/// and then keep trusting an older cached one.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum LicenseStatus {
    Active,
    Revoked,
    Expired,
    #[serde(other)]
    Unknown,
}

/// The fields the server signed. Only ever constructed by [`verify_signed`]
/// (or its keyring-parameterised sibling), which is what lets the rest of
/// the app treat an instance as trustworthy.
///
/// Unknown JSON fields are ignored (no `deny_unknown_fields`) so the server
/// can add to the payload without an app release — additions are covered by
/// the signature just the same, they simply aren't read by this build.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LicensePayload {
    pub v: u32,
    pub kid: String,
    pub license_key: String,
    pub status: LicenseStatus,
    /// Server unix time when this payload was signed. Doubles as a floor
    /// for the local clock and as the ordering between competing payloads.
    pub issued_at: i64,
    /// Unix time, or `None` for a perpetual licence.
    pub expires_at: Option<i64>,
    /// The hex fingerprint the app sent, echoed back. The app compares it
    /// against its own so a payload copied from another machine fails.
    pub device_fingerprint: String,
    /// How long the app may run without a successful online refresh before
    /// it insists on one. Server-controlled so policy needs no app release.
    pub max_offline_days: u32,
}

#[derive(Debug, PartialEq, Eq, thiserror::Error)]
pub enum VerifyError {
    /// Base64 or JSON that couldn't be read at all. Carries no detail on
    /// purpose beyond what's needed to debug a genuine server bug.
    #[error("Licence data is malformed ({0})")]
    Malformed(&'static str),
    /// The payload names a key id this build doesn't ship.
    #[error("Licence was signed with a key this version of the app does not recognise ({0}) — please update the app")]
    UnknownKeyId(String),
    /// The bytes do not verify under the named key. The one error that
    /// means "someone changed something".
    #[error("Licence data failed verification")]
    BadSignature,
    /// Signature is fine, but the shape is newer than this build reads.
    #[error("Licence data is in a newer format (v{0}) than this version of the app understands — please update the app")]
    UnsupportedVersion(u32),
}

/// Verifies a payload from `api/license-status.php` (or the local cache of
/// one) under the compiled-in [`ACCEPTED_PUBLIC_KEYS`].
pub fn verify_signed(payload_b64: &str, signature_b64: &str) -> Result<LicensePayload, VerifyError> {
    verify_with_keys(ACCEPTED_PUBLIC_KEYS, payload_b64, signature_b64)
}

/// The kid a payload claims, read *before* verification. Nothing else is
/// looked at until the signature has been checked under that key — an
/// attacker choosing the kid can at most pick which of our keys we verify
/// with, never supply one.
#[derive(Deserialize)]
struct KidOnly {
    kid: String,
}

/// [`verify_signed`] with an explicit keyring, so the tests can exercise
/// every path with a throwaway keypair instead of the production key.
pub fn verify_with_keys(
    keys: &[(&str, [u8; 32])],
    payload_b64: &str,
    signature_b64: &str,
) -> Result<LicensePayload, VerifyError> {
    let payload = BASE64
        .decode(payload_b64.trim())
        .map_err(|_| VerifyError::Malformed("payload is not base64"))?;
    let signature_bytes = BASE64
        .decode(signature_b64.trim())
        .map_err(|_| VerifyError::Malformed("signature is not base64"))?;
    let signature = Signature::from_slice(&signature_bytes)
        .map_err(|_| VerifyError::Malformed("signature has the wrong length"))?;

    let claimed: KidOnly =
        serde_json::from_slice(&payload).map_err(|_| VerifyError::Malformed("payload is not JSON"))?;
    let (_, key_bytes) = keys
        .iter()
        .find(|(kid, _)| *kid == claimed.kid)
        .ok_or_else(|| VerifyError::UnknownKeyId(claimed.kid.clone()))?;
    let key = VerifyingKey::from_bytes(key_bytes).map_err(|_| VerifyError::Malformed("embedded key"))?;

    // `verify_strict` additionally rejects the small-order / non-canonical
    // point encodings that plain `verify` tolerates. Nothing legitimate the
    // server produces ever hits that difference, so the stricter check
    // costs nothing and removes a class of malleability.
    key.verify_strict(&payload, &signature).map_err(|_| VerifyError::BadSignature)?;

    // Signature checked — now, and only now, read the rest.
    let parsed: LicensePayload =
        serde_json::from_slice(&payload).map_err(|_| VerifyError::Malformed("payload fields"))?;
    if parsed.v != PAYLOAD_VERSION {
        return Err(VerifyError::UnsupportedVersion(parsed.v));
    }
    Ok(parsed)
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use ed25519_dalek::{Signer, SigningKey};

    /// A deterministic throwaway keypair. This seed is public by definition
    /// (it's in the repo) and is never listed in `ACCEPTED_PUBLIC_KEYS`, so
    /// nothing it signs is accepted by a real build — that's exactly what
    /// `the_test_key_is_not_an_accepted_key` pins down.
    pub(crate) const TEST_SEED: [u8; 32] = [7u8; 32];
    pub(crate) const TEST_KID: &str = "test";

    pub(crate) fn test_signing_key() -> SigningKey {
        SigningKey::from_bytes(&TEST_SEED)
    }

    pub(crate) fn test_keyring() -> Vec<(&'static str, [u8; 32])> {
        vec![(TEST_KID, test_signing_key().verifying_key().to_bytes())]
    }

    /// Mirrors the server's wire form exactly: base64 of the JSON bytes,
    /// signature over those same bytes.
    pub(crate) fn sign_json(json: &str) -> (String, String) {
        let sig = test_signing_key().sign(json.as_bytes());
        (BASE64.encode(json.as_bytes()), BASE64.encode(sig.to_bytes()))
    }

    pub(crate) fn sample_json() -> String {
        format!(
            r#"{{"v":1,"kid":"{TEST_KID}","license_key":"DIWAN-AAAA-BBBB-CCCC-DDDD","status":"active","issued_at":1757700000,"expires_at":1760292000,"device_fingerprint":"{}","max_offline_days":30}}"#,
            "ab".repeat(32)
        )
    }

    fn verify(json: &str) -> Result<LicensePayload, VerifyError> {
        let (p, s) = sign_json(json);
        verify_with_keys(&test_keyring(), &p, &s)
    }

    // --- the compiled-in constants -------------------------------------------

    /// A typo in a hex literal would ship a build that verifies nothing.
    #[test]
    fn every_accepted_public_key_is_a_valid_ed25519_key() {
        assert!(!ACCEPTED_PUBLIC_KEYS.is_empty());
        for (kid, bytes) in ACCEPTED_PUBLIC_KEYS {
            assert!(VerifyingKey::from_bytes(bytes).is_ok(), "key {kid} is not a valid point");
            assert!(!kid.is_empty());
        }
    }

    #[test]
    fn accepted_key_ids_are_unique() {
        for (i, (a, _)) in ACCEPTED_PUBLIC_KEYS.iter().enumerate() {
            assert!(!ACCEPTED_PUBLIC_KEYS[i + 1..].iter().any(|(b, _)| b == a), "duplicate kid {a}");
        }
    }

    /// The in-repo test key must never be able to unlock a real build.
    #[test]
    fn the_test_key_is_not_an_accepted_key() {
        let test_pk = test_signing_key().verifying_key().to_bytes();
        assert!(ACCEPTED_PUBLIC_KEYS.iter().all(|(kid, pk)| *pk != test_pk && *kid != TEST_KID));
    }

    // --- the happy path ---------------------------------------------------------

    #[test]
    fn a_correctly_signed_payload_verifies_and_parses() {
        let parsed = verify(&sample_json()).expect("should verify");
        assert_eq!(parsed.v, 1);
        assert_eq!(parsed.kid, TEST_KID);
        assert_eq!(parsed.license_key, "DIWAN-AAAA-BBBB-CCCC-DDDD");
        assert_eq!(parsed.status, LicenseStatus::Active);
        assert_eq!(parsed.issued_at, 1757700000);
        assert_eq!(parsed.expires_at, Some(1760292000));
        assert_eq!(parsed.device_fingerprint, "ab".repeat(32));
        assert_eq!(parsed.max_offline_days, 30);
    }

    #[test]
    fn a_perpetual_licence_has_no_expiry() {
        let json = sample_json().replace(r#""expires_at":1760292000"#, r#""expires_at":null"#);
        assert_eq!(verify(&json).unwrap().expires_at, None);
    }

    #[test]
    fn every_known_status_parses_and_unknown_ones_fail_closed() {
        for (wire, expected) in [
            ("active", LicenseStatus::Active),
            ("revoked", LicenseStatus::Revoked),
            ("expired", LicenseStatus::Expired),
            ("suspended", LicenseStatus::Unknown),
        ] {
            let json = sample_json().replace(r#""status":"active""#, &format!(r#""status":"{wire}""#));
            assert_eq!(verify(&json).unwrap().status, expected, "status {wire}");
        }
    }

    /// The server may grow the payload without an app release.
    #[test]
    fn extra_fields_are_ignored_but_still_covered_by_the_signature() {
        let json = sample_json().replace(r#""max_offline_days":30}"#, r#""max_offline_days":30,"future":"x"}"#);
        assert!(verify(&json).is_ok());
    }

    /// Whitespace around a stored base64 string (a trailing newline from a
    /// copy-paste in the settings screen) must not turn into "tampered".
    #[test]
    fn surrounding_whitespace_in_the_encoded_strings_is_tolerated() {
        let (p, s) = sign_json(&sample_json());
        assert!(verify_with_keys(&test_keyring(), &format!(" {p}\n"), &format!("{s} ")).is_ok());
    }

    // --- tampering ----------------------------------------------------------------

    /// The attack this whole module exists for: edit the cached expiry.
    #[test]
    fn editing_the_expiry_after_signing_is_rejected() {
        let (_, sig) = sign_json(&sample_json());
        let edited = sample_json().replace("1760292000", "4102444800"); // → 2100
        let result = verify_with_keys(&test_keyring(), &BASE64.encode(edited.as_bytes()), &sig);
        assert_eq!(result, Err(VerifyError::BadSignature));
    }

    #[test]
    fn editing_the_status_after_signing_is_rejected() {
        let revoked = sample_json().replace(r#""status":"active""#, r#""status":"revoked""#);
        let (_, sig) = sign_json(&revoked);
        let laundered = BASE64.encode(sample_json().as_bytes());
        assert_eq!(verify_with_keys(&test_keyring(), &laundered, &sig), Err(VerifyError::BadSignature));
    }

    /// Even a semantically identical re-serialisation (key order, spacing)
    /// is a different byte string and must fail — there is exactly one
    /// canonical form, and it is the one the server signed.
    #[test]
    fn reserialised_json_with_the_same_meaning_is_rejected() {
        let (_, sig) = sign_json(&sample_json());
        let respaced = sample_json().replace(",", ", ");
        assert_eq!(
            verify_with_keys(&test_keyring(), &BASE64.encode(respaced.as_bytes()), &sig),
            Err(VerifyError::BadSignature)
        );
    }

    #[test]
    fn a_signature_from_a_different_key_is_rejected() {
        let other = SigningKey::from_bytes(&[9u8; 32]);
        let json = sample_json();
        let sig = other.sign(json.as_bytes());
        let result = verify_with_keys(&test_keyring(), &BASE64.encode(json.as_bytes()), &BASE64.encode(sig.to_bytes()));
        assert_eq!(result, Err(VerifyError::BadSignature));
    }

    /// Choosing the kid buys an attacker nothing: it selects which of OUR
    /// keys we check under, and a payload signed by anyone else fails.
    #[test]
    fn a_payload_naming_an_unknown_key_id_is_rejected_before_parsing() {
        let json = sample_json().replace(&format!(r#""kid":"{TEST_KID}""#), r#""kid":"nope""#);
        assert_eq!(verify(&json), Err(VerifyError::UnknownKeyId("nope".into())));
    }

    /// Pointing a payload at the real production kid while signing with the
    /// test key must fail under the real keyring — i.e. the only way to
    /// produce something a shipped build accepts is to hold the real
    /// private key.
    #[test]
    fn the_production_keyring_rejects_anything_the_test_key_signed() {
        let real_kid = ACCEPTED_PUBLIC_KEYS[0].0;
        let json = sample_json().replace(&format!(r#""kid":"{TEST_KID}""#), &format!(r#""kid":"{real_kid}""#));
        let (p, s) = sign_json(&json);
        assert_eq!(verify_signed(&p, &s), Err(VerifyError::BadSignature));
    }

    #[test]
    fn a_newer_payload_version_is_rejected_even_when_correctly_signed() {
        let json = sample_json().replace(r#""v":1,"#, r#""v":2,"#);
        assert_eq!(verify(&json), Err(VerifyError::UnsupportedVersion(2)));
    }

    // --- malformed input ----------------------------------------------------------

    #[test]
    fn garbage_in_every_position_is_malformed_not_a_panic() {
        let (p, s) = sign_json(&sample_json());
        assert!(matches!(verify_with_keys(&test_keyring(), "not base64!", &s), Err(VerifyError::Malformed(_))));
        assert!(matches!(verify_with_keys(&test_keyring(), &p, "not base64!"), Err(VerifyError::Malformed(_))));
        assert!(matches!(verify_with_keys(&test_keyring(), &p, &BASE64.encode(b"short")), Err(VerifyError::Malformed(_))));
        assert!(matches!(verify_with_keys(&test_keyring(), &BASE64.encode(b"{not json"), &s), Err(VerifyError::Malformed(_))));
        assert!(matches!(verify_with_keys(&test_keyring(), "", ""), Err(VerifyError::Malformed(_))));
    }

    /// A signed payload that verifies but lacks a required field is still
    /// rejected — the signature proves the server sent it, not that this
    /// build can read it.
    #[test]
    fn a_verified_payload_missing_required_fields_is_malformed() {
        let json = format!(r#"{{"v":1,"kid":"{TEST_KID}","license_key":"DIWAN-X"}}"#);
        assert_eq!(verify(&json), Err(VerifyError::Malformed("payload fields")));
    }
}

