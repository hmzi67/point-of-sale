//! Android USB Host (USB-OTG) printer transport — the second Android
//! transport, alongside `android_bt`. Which one an install uses is
//! `AppConfig.printer_connection_type` (`"usb"` vs. `"bluetooth"`), chosen in
//! Settings; see `printer::escpos::send_to_printer_dispatch`.
//!
//! This exists because Bluetooth is not universal on till printers. The
//! client hardware that forced it — a Gainscha GA-E200, whose own label reads
//! "Interface: Serial & USB & Ethernet" — has no Bluetooth radio at all, so
//! the paired-device picker had nothing to offer it. It is plugged into the
//! Android device through a USB-OTG cable instead.
//!
//! **Not a revival of the old libusb attempt.** `rusb` was tried on Android
//! first and dropped — it crashed the whole app natively (a libusb-level
//! fault, not a catchable Rust panic), because libusb wants to open the
//! device node directly and Android does not let an app do that: USB access
//! there is mediated by `android.hardware.usb.UsbManager`, which hands out a
//! *file descriptor* only after the user has approved that specific device in
//! a system dialog. That permission model is precisely what this module goes
//! through, so it is the right shape for the platform rather than a fight
//! with it. See `Cargo.toml`'s comment on why `rusb` stays `cfg`'d out of
//! Android builds.
//!
//! The `JavaVM`/`Context` plumbing every call here depends on is shared with
//! `android_bt` and lives in `printer::android_jni` — read that module's doc
//! comment first.
//!
//! The bytes written are exactly the bytes `android_bt` writes and exactly
//! the bytes the desktop transports write: `printer::escpos` builds them,
//! `printer::layout`'s `LINE_WIDTH` sizes them, and this module is only a
//! pipe. "Print width test" therefore measures a USB-connected printer the
//! same way it measures any other, with no USB-specific path.
//!
//! Requires `<uses-feature android:name="android.hardware.usb.host" ...>` in
//! `AndroidManifest.xml` (declared `required="false"`, so the app still
//! installs on a phone with no OTG support — this is one printer transport of
//! several, not a hardware prerequisite for the app). `gen/android` is
//! gitignored and regenerated by `tauri android init`, so that declaration is
//! applied by `scripts/patch_android_manifest.py`. Unlike Bluetooth, USB host
//! access needs no manifest *permission* — the per-device runtime grant below
//! is the whole permission model.

use crate::printer::android_jni::{clear_exception, io_err, jstring_to_string, with_env};
use crate::printer::escpos::PrinterError;
use jni::objects::{JObject, JValue};
use jni::JNIEnv;

/// `Context.USB_SERVICE` — the string key `getSystemService` wants.
const USB_SERVICE: &str = "usb";

/// The broadcast action our permission `PendingIntent` carries. Nothing
/// listens for it (see [`request_permission`]); it only has to be unique to
/// this app, which the package-qualified name makes it.
const USB_PERMISSION_ACTION: &str = "com.diwan.pos.USB_PERMISSION";

/// `UsbConstants.USB_CLASS_PRINTER` — the standard USB base class for
/// printers, and the reliable half of [`UsbDeviceInfo::is_printer_class`].
const USB_CLASS_PRINTER: i32 = 7;
/// `UsbConstants.USB_DIR_OUT` — the direction bit value for host-to-device.
const USB_DIR_OUT: i32 = 0;
/// `UsbConstants.USB_ENDPOINT_XFER_BULK` — the transfer type ESC/POS data
/// goes over.
const USB_ENDPOINT_XFER_BULK: i32 = 2;

/// `PendingIntent.FLAG_IMMUTABLE`. Mandatory from API 31 (a `PendingIntent`
/// created without either mutability flag throws there) and available since
/// API 23, below this app's `minSdk` of 24 — so it is passed unconditionally
/// rather than version-gated. Immutable is also the correct choice on its own
/// merits: nothing needs to fill anything into this intent.
const FLAG_IMMUTABLE: i32 = 0x0400_0000;

/// How long a single bulk write may take before Android gives up on it, in
/// milliseconds. Matches the desktop USB transport's 5s: a receipt is small,
/// so this only has to cover a slow or busy printer, not a large transfer.
const BULK_TIMEOUT_MS: i32 = 5_000;

/// Bytes per `bulkTransfer` call. Android's own implementation has had a
/// 16 KB per-transfer ceiling historically and printers are happier with
/// steady small writes than one large one, so a whole receipt is written as a
/// sequence of chunks — see [`send`].
const CHUNK_SIZE: usize = 4096;

/// One attached USB device, as offered in Settings' printer picker.
pub struct UsbDeviceInfo {
    /// Human-readable label — the device's own product/manufacturer strings
    /// where it reports them, falling back to the VID:PID pair.
    pub name: String,
    /// The stable identifier this app stores and later matches on:
    /// `"vvvv:pppp"`, lowercase hex, vendor id then product id.
    ///
    /// Deliberately *not* `UsbDevice.getDeviceName()` (`/dev/bus/usb/001/002`
    /// and similar): that path encodes the bus and device number the kernel
    /// happened to assign this time, so it changes when the printer is
    /// unplugged and plugged back in — which for an OTG-connected till
    /// printer is a daily event, and would silently invalidate the saved
    /// selection every time.
    pub id: String,
    /// Whether this device advertises a standard Printer-class (0x07)
    /// interface. Used only to sort and label the picker, never to filter it:
    /// plenty of thermal printers — the Gainscha included — expose a
    /// vendor-specific class instead, so hiding everything else would hide
    /// exactly the printer this module was written for. The user picks.
    pub is_printer_class: bool,
    /// Whether the user has already approved this specific device. Android
    /// grants USB access per device, not per app, and the grant does not
    /// survive an unplug, so the picker shows this per row rather than as one
    /// app-wide state the way Bluetooth's permission is.
    pub has_permission: bool,
}

/// `"1a2b:3c4d"` from a vendor/product id pair — the format of
/// [`UsbDeviceInfo::id`] and of `AppConfig.printer_usb_device`.
fn device_id(vendor_id: i32, product_id: i32) -> String {
    format!("{vendor_id:04x}:{product_id:04x}")
}

/// `context.getSystemService(Context.USB_SERVICE)` as a `UsbManager`.
/// `None` means this device has no USB host support at all (the manifest
/// declares the feature `required="false"`, so the app does install on such
/// hardware) — a different situation from "no printer plugged in", and worth
/// a different message.
fn usb_manager<'a>(env: &mut JNIEnv<'a>, context: &JObject) -> Result<Option<JObject<'a>>, PrinterError> {
    let service_name = env.new_string(USB_SERVICE).map_err(|e| io_err(env, "service name alloc failed", e))?;
    let manager = env
        .call_method(
            context,
            "getSystemService",
            "(Ljava/lang/String;)Ljava/lang/Object;",
            &[JValue::Object(&service_name)],
        )
        .and_then(|v| v.l())
        .map_err(|e| io_err(env, "getSystemService(usb) failed", e))?;
    Ok(if manager.is_null() { None } else { Some(manager) })
}

/// The attached devices as a `java.lang.Object[]`, from
/// `UsbManager.getDeviceList().values().toArray()`.
fn device_array<'a>(
    env: &mut JNIEnv<'a>,
    manager: &JObject,
) -> Result<jni::objects::JObjectArray<'a>, PrinterError> {
    let map = env
        .call_method(manager, "getDeviceList", "()Ljava/util/HashMap;", &[])
        .and_then(|v| v.l())
        .map_err(|e| io_err(env, "getDeviceList failed", e))?;
    let values = env
        .call_method(&map, "values", "()Ljava/util/Collection;", &[])
        .and_then(|v| v.l())
        .map_err(|e| io_err(env, "device-map values failed", e))?;
    let array = env
        .call_method(&values, "toArray", "()[Ljava/lang/Object;", &[])
        .and_then(|v| v.l())
        .map_err(|e| io_err(env, "device-list toArray failed", e))?;
    Ok(jni::objects::JObjectArray::from(array))
}

fn int_method(env: &mut JNIEnv, obj: &JObject, method: &str, what: &str) -> Result<i32, PrinterError> {
    env.call_method(obj, method, "()I", &[]).and_then(|v| v.i()).map_err(|e| io_err(env, what, e))
}

/// A `UsbDevice` string getter that may legitimately return `null` (a device
/// is not required to carry product/manufacturer descriptor strings).
fn optional_string(env: &mut JNIEnv, device: &JObject, method: &str) -> Result<Option<String>, PrinterError> {
    let obj = env
        .call_method(device, method, "()Ljava/lang/String;", &[])
        .and_then(|v| v.l())
        .map_err(|e| io_err(env, &format!("UsbDevice.{method} failed"), e))?;
    if obj.is_null() {
        return Ok(None);
    }
    let s = jstring_to_string(env, obj)?;
    Ok(if s.trim().is_empty() { None } else { Some(s.trim().to_string()) })
}

/// Builds the picker label: the device's own product name, prefixed with the
/// manufacturer when that adds something, and falling back to the VID:PID
/// pair when the device reports neither. `getProductName`/
/// `getManufacturerName` are API 21+, below this app's `minSdk` of 24, so
/// they are always callable — they just aren't always populated.
fn display_name(env: &mut JNIEnv, device: &JObject, id: &str) -> Result<String, PrinterError> {
    let product = optional_string(env, device, "getProductName")?;
    let manufacturer = optional_string(env, device, "getManufacturerName")?;
    Ok(match (manufacturer, product) {
        (Some(m), Some(p)) if !p.to_lowercase().starts_with(&m.to_lowercase()) => format!("{m} {p}"),
        (_, Some(p)) => p,
        (Some(m), None) => format!("{m} ({id})"),
        (None, None) => format!("USB device {id}"),
    })
}

/// Whether any of `device`'s interfaces advertises the standard Printer
/// class. See [`UsbDeviceInfo::is_printer_class`] for why this only labels
/// and sorts the picker rather than filtering it.
fn has_printer_interface(env: &mut JNIEnv, device: &JObject) -> Result<bool, PrinterError> {
    let count = int_method(env, device, "getInterfaceCount", "getInterfaceCount failed")?;
    for i in 0..count {
        let iface = env
            .call_method(device, "getInterface", "(I)Landroid/hardware/usb/UsbInterface;", &[JValue::Int(i)])
            .and_then(|v| v.l())
            .map_err(|e| io_err(env, "getInterface failed", e))?;
        if int_method(env, &iface, "getInterfaceClass", "getInterfaceClass failed")? == USB_CLASS_PRINTER {
            return Ok(true);
        }
    }
    Ok(false)
}

fn has_permission(env: &mut JNIEnv, manager: &JObject, device: &JObject) -> Result<bool, PrinterError> {
    env.call_method(manager, "hasPermission", "(Landroid/hardware/usb/UsbDevice;)Z", &[JValue::Object(device)])
        .and_then(|v| v.z())
        .map_err(|e| io_err(env, "hasPermission check failed", e))
}

/// Every USB device currently attached — the candidate list for Settings'
/// printer picker in USB mode. Printer-class devices are listed first, since
/// when one is present it is almost certainly the intended answer, but
/// nothing is filtered out (see [`UsbDeviceInfo::is_printer_class`]).
///
/// Needs no permission of its own: enumerating attached devices and reading
/// their descriptors is unrestricted on Android; only *opening* one requires
/// the per-device grant.
pub fn list_devices() -> Result<Vec<UsbDeviceInfo>, PrinterError> {
    with_env(|env, context| {
        let Some(manager) = usb_manager(env, context)? else {
            return Err(PrinterError::Io("This device doesn't support USB host mode (USB-OTG)".into()));
        };
        let devices = device_array(env, &manager)?;
        let len = env.get_array_length(&devices).map_err(|e| io_err(env, "array length read failed", e))?;

        let mut out = Vec::with_capacity(len as usize);
        for i in 0..len {
            let device = env
                .get_object_array_element(&devices, i)
                .map_err(|e| io_err(env, "array element read failed", e))?;

            let vendor_id = int_method(env, &device, "getVendorId", "getVendorId failed")?;
            let product_id = int_method(env, &device, "getProductId", "getProductId failed")?;
            let id = device_id(vendor_id, product_id);

            out.push(UsbDeviceInfo {
                name: display_name(env, &device, &id)?,
                is_printer_class: has_printer_interface(env, &device)?,
                has_permission: has_permission(env, &manager, &device)?,
                id,
            });
        }

        out.sort_by(|a, b| b.is_printer_class.cmp(&a.is_printer_class).then_with(|| a.name.cmp(&b.name)));
        Ok(out)
    })
}

/// Runs `f` with the attached device whose VID:PID is `id`, or fails with a
/// message saying it isn't there — the single place "is the printer still
/// plugged in?" is answered, since [`permission_granted`], [`request_permission`]
/// and [`send`] all need the same lookup. `f` receives the `JNIEnv`, the
/// app `Context`, the `UsbManager` and the matched `UsbDevice`.
fn with_device<T>(
    id: &str,
    f: impl FnOnce(&mut JNIEnv, &JObject, &JObject, &JObject) -> Result<T, PrinterError>,
) -> Result<T, PrinterError> {
    with_env(|env, context| {
        let Some(manager) = usb_manager(env, context)? else {
            return Err(PrinterError::Io("This device doesn't support USB host mode (USB-OTG)".into()));
        };
        let devices = device_array(env, &manager)?;
        let len = env.get_array_length(&devices).map_err(|e| io_err(env, "array length read failed", e))?;

        for i in 0..len {
            let device = env
                .get_object_array_element(&devices, i)
                .map_err(|e| io_err(env, "array element read failed", e))?;
            let vendor_id = int_method(env, &device, "getVendorId", "getVendorId failed")?;
            let product_id = int_method(env, &device, "getProductId", "getProductId failed")?;
            if device_id(vendor_id, product_id) == id {
                return f(env, context, &manager, &device);
            }
        }

        Err(PrinterError::Io(
            "the selected USB printer isn't attached — check the OTG cable and that the printer is powered on".into(),
        ))
    })
}

/// Whether the user has approved this specific attached device.
///
/// Unlike Bluetooth's app-wide `BLUETOOTH_CONNECT`, an Android USB grant is
/// per `UsbDevice` and is dropped when the device is detached, so this is
/// asked per device and re-asked rather than cached.
pub fn permission_granted(id: &str) -> Result<bool, PrinterError> {
    with_device(id, |env, _context, manager, device| has_permission(env, manager, device))
}

/// Fires Android's system "Allow the app to access the USB device?" dialog
/// for this device, if it isn't already approved.
///
/// `UsbManager.requestPermission` takes a `PendingIntent` rather than needing
/// an `Activity`, which is why this can show the real in-app dialog where
/// `android_bt::request_permission` has to settle for opening the Settings
/// screen. The intent is package-scoped and `FLAG_IMMUTABLE` — both required
/// on recent Android versions for a `PendingIntent` handed to a system
/// service, and neither a constraint here since nothing needs to modify it.
///
/// Deliberately nothing receives the resulting broadcast: registering a
/// `BroadcastReceiver` would mean bridging its callback (delivered on the
/// main thread, whenever the user answers) back to whichever worker thread a
/// Tauri command runs on. The grant itself does not depend on anyone
/// listening — the system records it either way — so the Settings screen
/// simply re-checks [`permission_granted`] afterwards, the same
/// fire-and-forget-then-re-check shape the Bluetooth permission already uses.
///
/// A denial is therefore not an error here: it shows up as
/// [`permission_granted`] still returning `false`, and as
/// [`PrinterError::PermissionDenied`] from [`send`] — which callers already
/// treat as "fall back to the PDF receipt".
pub fn request_permission(id: &str) -> Result<(), PrinterError> {
    with_device(id, |env, context, manager, device| {
        if has_permission(env, manager, device)? {
            return Ok(());
        }

        let action = env.new_string(USB_PERMISSION_ACTION).map_err(|e| io_err(env, "action string alloc failed", e))?;
        let intent_class = env.find_class("android/content/Intent").map_err(|e| io_err(env, "Intent lookup failed", e))?;
        let intent = env
            .new_object(intent_class, "(Ljava/lang/String;)V", &[JValue::Object(&action)])
            .map_err(|e| io_err(env, "Intent construction failed", e))?;

        // Package-scoping an implicit intent is what keeps this legal on
        // API 34+, which rejects unrestricted implicit intents inside a
        // PendingIntent.
        let package_name = env
            .call_method(context, "getPackageName", "()Ljava/lang/String;", &[])
            .and_then(|v| v.l())
            .map_err(|e| io_err(env, "getPackageName failed", e))?;
        env.call_method(&intent, "setPackage", "(Ljava/lang/String;)Landroid/content/Intent;", &[JValue::Object(&package_name)])
            .map_err(|e| io_err(env, "setPackage failed", e))?;

        let pending = env
            .call_static_method(
                "android/app/PendingIntent",
                "getBroadcast",
                "(Landroid/content/Context;ILandroid/content/Intent;I)Landroid/app/PendingIntent;",
                &[JValue::Object(context), JValue::Int(0), JValue::Object(&intent), JValue::Int(FLAG_IMMUTABLE)],
            )
            .and_then(|v| v.l())
            .map_err(|e| io_err(env, "PendingIntent.getBroadcast failed", e))?;

        env.call_method(
            manager,
            "requestPermission",
            "(Landroid/hardware/usb/UsbDevice;Landroid/app/PendingIntent;)V",
            &[JValue::Object(device), JValue::Object(&pending)],
        )
        .map(|_| ())
        .map_err(|e| io_err(env, "requestPermission failed", e))
    })
}

/// The interface index and endpoint of the first bulk OUT endpoint on
/// `device` — where ESC/POS bytes go.
///
/// Prefers an interface that declares the standard Printer class, then falls
/// back to any interface with a bulk OUT endpoint. The fallback is the part
/// that matters in practice: the Gainscha GA-E200 and many other thermal
/// printers present a vendor-specific interface class, and a strict
/// Printer-class-only search would find nothing on exactly the hardware this
/// module exists for.
fn find_bulk_out<'a>(
    env: &mut JNIEnv<'a>,
    device: &JObject,
) -> Result<(JObject<'a>, JObject<'a>), PrinterError> {
    let count = int_method(env, device, "getInterfaceCount", "getInterfaceCount failed")?;

    // Two passes so a Printer-class interface always wins over an earlier
    // vendor-specific one on a composite device.
    for printer_class_only in [true, false] {
        for i in 0..count {
            let iface = env
                .call_method(device, "getInterface", "(I)Landroid/hardware/usb/UsbInterface;", &[JValue::Int(i)])
                .and_then(|v| v.l())
                .map_err(|e| io_err(env, "getInterface failed", e))?;

            if printer_class_only
                && int_method(env, &iface, "getInterfaceClass", "getInterfaceClass failed")? != USB_CLASS_PRINTER
            {
                continue;
            }

            let endpoints = int_method(env, &iface, "getEndpointCount", "getEndpointCount failed")?;
            for e in 0..endpoints {
                let endpoint = env
                    .call_method(&iface, "getEndpoint", "(I)Landroid/hardware/usb/UsbEndpoint;", &[JValue::Int(e)])
                    .and_then(|v| v.l())
                    .map_err(|err| io_err(env, "getEndpoint failed", err))?;
                let direction = int_method(env, &endpoint, "getDirection", "endpoint getDirection failed")?;
                let kind = int_method(env, &endpoint, "getType", "endpoint getType failed")?;
                if direction == USB_DIR_OUT && kind == USB_ENDPOINT_XFER_BULK {
                    return Ok((iface, endpoint));
                }
            }
        }
    }

    Err(PrinterError::Io("that USB device has no bulk output endpoint — it may not be a printer".into()))
}

/// Opens the attached device whose VID:PID is `id`, writes `bytes` to its
/// bulk OUT endpoint, and closes it — one shot per print, no connection kept
/// open between sales, matching `android_bt::send`.
///
/// The device must already have been approved; this returns
/// [`PrinterError::PermissionDenied`] rather than firing the system dialog,
/// because a print is triggered from the billing screen (often right after a
/// sale is already committed) and a modal permission prompt is not something
/// to spring on a cashier mid-receipt. Settings is where the grant is
/// obtained, once — see [`request_permission`].
pub fn send(id: &str, bytes: &[u8]) -> Result<(), PrinterError> {
    with_device(id, |env, _context, manager, device| {
        if !has_permission(env, manager, device)? {
            return Err(PrinterError::PermissionDenied);
        }

        let connection = env
            .call_method(
                manager,
                "openDevice",
                "(Landroid/hardware/usb/UsbDevice;)Landroid/hardware/usb/UsbDeviceConnection;",
                &[JValue::Object(device)],
            )
            .and_then(|v| v.l())
            .map_err(|e| io_err(env, "couldn't open the USB printer", e))?;
        if connection.is_null() {
            return Err(PrinterError::Io("couldn't open the USB printer — another app may be holding it".into()));
        }

        // From here on every exit path has to close the connection, so the
        // work is done in a closure and the result handled once below.
        let result = (|env: &mut JNIEnv| -> Result<(), PrinterError> {
            let (interface, endpoint) = find_bulk_out(env, device)?;

            // `force = true` takes the interface back from any kernel driver
            // that claimed it first, which is what a printer-class device
            // attaching to Android's own usblp-style handling looks like.
            let claimed = env
                .call_method(
                    &connection,
                    "claimInterface",
                    "(Landroid/hardware/usb/UsbInterface;Z)Z",
                    &[JValue::Object(&interface), JValue::Bool(1)],
                )
                .and_then(|v| v.z())
                .map_err(|e| io_err(env, "claimInterface failed", e))?;
            if !claimed {
                return Err(PrinterError::Io("couldn't claim the USB printer interface".into()));
            }

            let write = (|env: &mut JNIEnv| -> Result<(), PrinterError> {
                for chunk in bytes.chunks(CHUNK_SIZE) {
                    let buffer =
                        env.byte_array_from_slice(chunk).map_err(|e| io_err(env, "byte array alloc failed", e))?;
                    let written = env
                        .call_method(
                            &connection,
                            "bulkTransfer",
                            "(Landroid/hardware/usb/UsbEndpoint;[BII)I",
                            &[
                                JValue::Object(&endpoint),
                                JValue::Object(&buffer),
                                JValue::Int(chunk.len() as i32),
                                JValue::Int(BULK_TIMEOUT_MS),
                            ],
                        )
                        .and_then(|v| v.i())
                        .map_err(|e| io_err(env, "USB write failed", e))?;

                    // bulkTransfer returns bytes transferred, or a negative
                    // value on failure. A short write is a failure too: a
                    // half-written receipt is worse than none, since the
                    // caller's PDF fallback then prints the whole thing again.
                    if written < 0 {
                        return Err(PrinterError::Io(
                            "the USB printer stopped accepting data — check it has paper and is powered on".into(),
                        ));
                    }
                    if written as usize != chunk.len() {
                        return Err(PrinterError::Io("the USB printer accepted only part of the receipt".into()));
                    }
                }
                Ok(())
            })(env);

            let _ = env.call_method(
                &connection,
                "releaseInterface",
                "(Landroid/hardware/usb/UsbInterface;)Z",
                &[JValue::Object(&interface)],
            );
            write
        })(env);

        // `close()` runs on every exit path, including ones already carrying
        // an error — so any exception *it* raises is cleared here rather than
        // left pending to surface at some unrelated JNI call later. Same
        // discipline as `android_jni::io_err`, for a call whose result is
        // deliberately ignored.
        let _ = env.call_method(&connection, "close", "()V", &[]);
        clear_exception(env);
        result
    })
}
